def build_production_evaluation_cases() -> Tuple[EvaluationCase, ...]:
    """把预定位的真实证据编译为 EvaluationCase（不重新分块）。"""
    cases: List[EvaluationCase] = []
    for index, spec in enumerate(RAW_SPECS):
        cases.append(
            EvaluationCase(
                case_id=index + 1,
                case_key=spec["case_key"],
                category=spec["category"],
                difficulty=spec["difficulty"],
                expected_document_ids=tuple(
                    ev["document_id"] for ev in spec["evidence"]
                ),
                expected_status=spec["expected_status"],
                review_note=spec["rationale"],
                query=spec["query"],
                expected_evidence=tuple(spec["evidence"]),
                tags=tuple(spec.get("tags", [])),
            )
        )
    return tuple(cases)


PRODUCTION_EVALUATION_CASES: Tuple[EvaluationCase, ...] = (
    build_production_evaluation_cases()
)

