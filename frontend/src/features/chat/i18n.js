// 无完整翻译的语言回退：繁体回退简体，其余回退英文
const FALLBACK = { 'zh-TW': 'zh-CN', fr: 'en', ru: 'en', ja: 'en', vi: 'en' }

const current = ref('zh-CN')

function resolveLang(lang) {
  if (messages[lang]) return lang
  return FALLBACK[lang] || 'en'
}

export function setLanguage(lang) {
  current.value = resolveLang(lang)
}

export function useI18n() {
  const t = (key, params = {}) => {
    const dict = messages[current.value] || messages['zh-CN']
    let text = dict[key] ?? messages['zh-CN'][key] ?? key
    for (const [k, v] of Object.entries(params)) {
      text = text.split(`{${k}}`).join(String(v))
    }
    return text
  }
  return { t, lang: current }
}
